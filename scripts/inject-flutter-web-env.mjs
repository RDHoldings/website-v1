/**
 * Writes dist/precision-pilot and precision-pilot-test app/assets/.env from env.
 * Used after Vite copies public/ so Flutter web can read keys at runtime.
 *
 * SECURITY: Anything written here is served as a static file — visible to every visitor.
 * Use only browser-safe keys (Google HTTP referrer restrictions, HERE app creds, etc.).
 * Never commit real values under public/; CI injects into dist/ only.
 *
 * Server-only keys (e.g. Resend) are skipped unless INJECT_FLUTTER_WEB_INCLUDE_RESEND=true.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = fileURLToPath(new URL('.', import.meta.url))
const root = join(__dirname, '..')

/** Keys the Flutter app reads from assets/.env (match your Dart env names). */
const CLIENT_ENV_KEYS = [
  'GOOGLE_PLACES_API_KEY',
  'GOOGLE_CLOUD_VISION_API_KEY',
  'GOOGLE_MAPS_API_KEY',
  'HERE_API_KEY',
  'HERE_APP_ID',
  'ACCUWEATHER_API_KEY',
  'EIA_API_KEY',
  'APP_INVITE_BASE_URL',
]

const includeResend = process.env.INJECT_FLUTTER_WEB_INCLUDE_RESEND === 'true'
if (includeResend) {
  console.warn(
    'inject-flutter-web-env: RESEND_API_KEY will be embedded in the client bundle (public to all visitors). Prefer a backend for email.',
  )
}

const optionalKeys = includeResend ? ['RESEND_API_KEY'] : []
const allKeys = [...CLIENT_ENV_KEYS, ...optionalKeys]

function escapeEnvValue(value) {
  const s = String(value)
  if (/[\s#"'\\]/.test(s) || s.includes('=')) {
    return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
  }
  return s
}

function buildEnvContent() {
  const lines = [
    '# Generated by scripts/inject-flutter-web-env.mjs — do not commit dist/.',
    '# Values come from the build environment (e.g. GitHub Actions secrets).',
    '# Anyone can read this file from the deployed site; restrict keys in provider consoles.',
    '',
  ]
  let count = 0
  for (const key of allKeys) {
    const raw = process.env[key]
    if (raw === undefined || raw === null) continue
    const trimmed = String(raw).trim()
    if (trimmed === '') continue
    lines.push(`${key}=${escapeEnvValue(trimmed)}`)
    count += 1
  }
  if (count === 0) {
    lines.push(
      '# (no keys injected — set repository secrets / env vars for this build)',
    )
  }
  return lines.join('\n') + '\n'
}

const embeds = ['precision-pilot', 'precision-pilot-test']
const content = buildEnvContent()

for (const name of embeds) {
  const envPath = join(root, 'dist', name, 'app', 'assets', '.env')
  if (!existsSync(dirname(envPath))) {
    mkdirSync(dirname(envPath), { recursive: true })
  }
  writeFileSync(envPath, content, 'utf8')
  console.log(`inject-flutter-web-env: wrote ${envPath}`)
}
